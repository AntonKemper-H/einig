"""Database access. This is the only module that talks to the database.

Two databases, one interface (docs/decisions.md, D4; specs/c1-deployment.md):
- SQLite locally and in tests (a file in instance/ or a temporary file).
- Hosted Postgres when deployed, if the secret DATABASE_URL is set.

All SQL in this project is written in SQLite style with "?" placeholders.
For Postgres, this module translates it, so the rest of the code never has to
know which database is running. Rows must be read by column name (row["id"]).
"""

import re
import sqlite3
from collections.abc import Iterator
from contextlib import contextmanager
from pathlib import Path

import click
import psycopg
from flask import Flask, current_app, g
from flask.cli import with_appcontext
from psycopg.rows import dict_row

SCHEMA_FILE = Path(__file__).parent / "schema.sql"

# Catch these to handle a broken UNIQUE rule (e.g. a second veto) on both databases.
INTEGRITY_ERRORS = (sqlite3.IntegrityError, psycopg.IntegrityError)

# Postgres version of SQLite's CURRENT_TIMESTAMP: UTC as text 'YYYY-MM-DD HH:MM:SS'.
# Same format on both databases, so times still compare correctly as text (deadline, F11).
POSTGRES_UTC_NOW = "to_char(now() AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS')"


# --- Translating SQLite-style SQL for Postgres -------------------------------------

def to_postgres_sql(sql: str) -> str:
    """Turn "?" placeholders into "%s" for psycopg; keep "?" inside quoted text."""
    translated = []
    inside_quotes = False
    for character in sql:
        if character == "'":
            inside_quotes = not inside_quotes
            translated.append(character)
        elif character == "%":
            # psycopg reads a single % as the start of a placeholder, so a real % is written %%.
            translated.append("%%")
        elif character == "?" and not inside_quotes:
            translated.append("%s")
        else:
            translated.append(character)
    return "".join(translated)


def schema_to_postgres(script: str) -> str:
    """Translate schema.sql from SQLite to Postgres, so schema.sql stays the only schema file."""
    # Comments go first: they mention SQLite words that must not be translated.
    lines_without_comments = [line.split("--", 1)[0] for line in script.splitlines()]
    script = "\n".join(lines_without_comments)
    # SQLite counts an INTEGER PRIMARY KEY up by itself; Postgres needs to be told.
    script = script.replace(
        "INTEGER PRIMARY KEY", "INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY"
    )
    script = script.replace("DEFAULT CURRENT_TIMESTAMP", "DEFAULT " + POSTGRES_UTC_NOW)
    # "INSERT OR IGNORE" is SQLite only; Postgres writes "ON CONFLICT DO NOTHING" at the end.
    script = re.sub(
        r"INSERT OR IGNORE INTO (.*?);",
        r"INSERT INTO \1 ON CONFLICT DO NOTHING;",
        script,
        flags=re.DOTALL,
    )
    return script


class PostgresConnection:
    """Wraps a psycopg connection so it accepts the same "?" SQL as SQLite."""

    def __init__(self, connection: psycopg.Connection) -> None:
        self.connection = connection

    def execute(self, sql: str, params: tuple | list = ()) -> psycopg.Cursor:
        """Run one statement. Parameters are always passed, so psycopg reads %% as %."""
        return self.connection.execute(to_postgres_sql(sql), tuple(params))

    def executescript(self, script: str) -> None:
        """Run several statements at once (only possible without parameters)."""
        self.connection.execute(script)

    def commit(self) -> None:
        self.connection.commit()

    def rollback(self) -> None:
        self.connection.rollback()

    def close(self) -> None:
        self.connection.close()


# --- Connection handling ----------------------------------------------------------

def using_postgres() -> bool:
    """True when the app is configured with a DATABASE_URL (the deployed app)."""
    return bool(current_app.config.get("DATABASE_URL"))


def get_db() -> sqlite3.Connection | PostgresConnection:
    """Return the database connection for the current request, opening it if needed."""
    if "db" not in g:
        if using_postgres():
            # dict_row: rows behave like dicts, row["title"], as with SQLite below.
            g.db = PostgresConnection(
                psycopg.connect(current_app.config["DATABASE_URL"], row_factory=dict_row)
            )
        else:
            g.db = sqlite3.connect(current_app.config["DATABASE"])
            g.db.row_factory = sqlite3.Row  # rows behave like dicts: row["title"]
            # SQLite ignores foreign keys unless asked; Postgres always checks them.
            g.db.execute("PRAGMA foreign_keys = ON")
    return g.db


@contextmanager
def transaction() -> Iterator[sqlite3.Connection | PostgresConnection]:
    """Run the statements inside the block as one unit: all are saved, or none.

    Use this instead of "with connection:". In psycopg, "with connection:" also
    closes the connection, so later queries in the same request would fail.
    """
    connection = get_db()
    try:
        yield connection
    except BaseException:
        connection.rollback()
        raise
    connection.commit()


def close_db(error: BaseException | None = None) -> None:
    """Close the connection at the end of the request, if one was opened."""
    connection = g.pop("db", None)
    if connection is not None:
        connection.close()


def init_db() -> None:
    """Create all missing tables from schema.sql. Existing data is never deleted."""
    script = SCHEMA_FILE.read_text(encoding="utf-8")
    if using_postgres():
        script = schema_to_postgres(script)
    connection = get_db()
    connection.executescript(script)
    connection.commit()


def reset_db() -> None:
    """Delete every table with all its data, then create empty tables again."""
    connection = get_db()
    # Table names cannot be "?" placeholders. They come from the database itself, not from a user.
    if using_postgres():
        rows = connection.execute(
            "SELECT table_name FROM information_schema.tables"
            " WHERE table_schema = 'public' AND table_type = 'BASE TABLE'"
        ).fetchall()
        for row in rows:
            # CASCADE also removes foreign keys from other tables that point here.
            connection.execute(f'DROP TABLE "{row["table_name"]}" CASCADE')
    else:
        rows = connection.execute(
            "SELECT name FROM sqlite_master WHERE type = 'table' AND name NOT LIKE 'sqlite_%'"
        ).fetchall()
        # Foreign keys would block dropping tables that others point to.
        connection.execute("PRAGMA foreign_keys = OFF")
        for row in rows:
            connection.execute(f'DROP TABLE "{row["name"]}"')
        connection.execute("PRAGMA foreign_keys = ON")
    connection.commit()
    init_db()


def create_room_with_creator(
    room_id: str, title: str, mode: str, nickname: str, session_token: str
) -> bool:
    """Save a new room and its creator in one transaction. Return False if an id or token already exists."""
    try:
        # Both inserts are saved together, or both are rolled back on an error,
        # so there is never a room without its creator.
        with transaction() as connection:
            connection.execute(
                "INSERT INTO rooms (id, title, mode) VALUES (?, ?, ?)",
                (room_id, title, mode),
            )
            connection.execute(
                "INSERT INTO participants (room_id, nickname, session_token, is_creator)"
                " VALUES (?, ?, ?, 1)",
                (room_id, nickname, session_token),
            )
    except INTEGRITY_ERRORS:
        # A duplicate room id or session token (extremely unlikely with random tokens).
        return False
    return True


def get_room(room_id: str) -> sqlite3.Row | dict | None:
    """Return the room with this id, or None if it does not exist."""
    return get_db().execute(
        "SELECT id, title, mode, status FROM rooms WHERE id = ?", (room_id,)
    ).fetchone()


def get_participant(room_id: str, session_token: str | None) -> sqlite3.Row | dict | None:
    """Return the participant of this room with this session token, or None."""
    if not session_token:
        return None
    return get_db().execute(
        "SELECT id, nickname, is_creator, has_finished FROM participants"
        " WHERE room_id = ? AND session_token = ?",
        (room_id, session_token),
    ).fetchone()


def get_nicknames(room_id: str) -> list[str]:
    """Return the nicknames of all participants in this room."""
    rows = get_db().execute(
        "SELECT nickname FROM participants WHERE room_id = ?", (room_id,)
    ).fetchall()
    return [row["nickname"] for row in rows]


def add_participant(room_id: str, nickname: str, session_token: str) -> bool:
    """Save a new (non-creator) participant. Return False if the database refuses it."""
    try:
        # db.transaction() instead of "with connection:", which would close a Postgres connection.
        with transaction() as connection:
            connection.execute(
                "INSERT INTO participants (room_id, nickname, session_token) VALUES (?, ?, ?)",
                (room_id, nickname, session_token),
            )
    except INTEGRITY_ERRORS:
        # Duplicate token, or the same nickname saved by another request a moment earlier.
        return False
    return True


def get_options(room_id: str) -> list[sqlite3.Row | dict]:
    """Return all options of a room in the order they were added."""
    return get_db().execute(
        "SELECT id, label FROM options WHERE room_id = ? ORDER BY id",
        (room_id,),
    ).fetchall()


def get_option_labels(room_id: str) -> list[str]:
    """Return the labels of all manual options in this room (used for the duplicate check)."""
    rows = get_db().execute(
        "SELECT label FROM options WHERE room_id = ? AND label IS NOT NULL", (room_id,)
    ).fetchall()
    return [row["label"] for row in rows]


def add_manual_option(room_id: str, label: str) -> bool:
    """Save a manually entered option. Return False if the database refuses it."""
    try:
        # db.transaction() instead of "with connection:", which would close a Postgres connection.
        with transaction() as connection:
            connection.execute(
                "INSERT INTO options (room_id, source, label) VALUES (?, 'manual', ?)",
                (room_id, label),
            )
    except INTEGRITY_ERRORS:
        # The same label saved by another request a moment earlier (UNIQUE room_id, label).
        return False
    return True


def get_participants(room_id: str) -> list[sqlite3.Row | dict]:
    """Return all participants of a room in the order they joined (for the lobby)."""
    return get_db().execute(
        "SELECT id, nickname, is_creator, has_finished FROM participants"
        " WHERE room_id = ? ORDER BY id",
        (room_id,),
    ).fetchall()


def start_voting(room_id: str) -> bool:
    """Switch the room from collecting to voting. Return False if it was no longer collecting."""
    # "AND status = 'collecting'" makes two starts at the same moment change the room
    # only once: the second UPDATE finds no matching row.
    with transaction() as connection:
        cursor = connection.execute(
            "UPDATE rooms SET status = 'voting' WHERE id = ? AND status = 'collecting'",
            (room_id,),
        )
    return cursor.rowcount == 1


@click.command("init-db")
@with_appcontext  # gives the command access to the app config and get_db()
def init_db_command() -> None:
    """CLI: uv run flask --app app init-db (safe: only creates what is missing)."""
    init_db()
    click.echo("Initialized the database.")


@click.command("reset-db")
@with_appcontext
def reset_db_command() -> None:
    """CLI: uv run flask --app app reset-db (deletes all data after confirmation)."""
    if not click.confirm("This will delete all data in the database. Continue?", default=False):
        click.echo("Cancelled. Nothing was changed.")
        return
    reset_db()
    click.echo("Database reset. All tables are empty.")


def init_app(app: Flask) -> None:
    """Register the close handler and the database commands with the app."""
    app.teardown_appcontext(close_db)
    app.cli.add_command(init_db_command)
    app.cli.add_command(reset_db_command)
